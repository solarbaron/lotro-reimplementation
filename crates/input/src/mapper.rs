//! The runtime: raw events in, per-frame action states out
//! (`docs/specs/keymap.md` §7).
//!
//! Frame protocol:
//!
//! 1. feed every window/device event with [`InputMapper::handle`];
//! 2. call [`InputMapper::update`] once, which publishes a snapshot;
//! 3. read the snapshot ([`InputMapper::state`], [`InputMapper::text`]) until
//!    the next `update`.
//!
//! Edges (`presses`, `releases`) and relative deltas that happen between two
//! `update` calls all land in the second snapshot, so nothing is lost when a
//! key is pressed and released inside one frame.

use std::time::Duration;

use crate::action::{
    ActionDef, ActionId, ActionKind, ContextDef, ContextId, ModifierPolicy, Registry,
};
use crate::chord::{Chord, Stroke};
use crate::device::{
    AnalogAxis, Button, KeyCode, Modifiers, MouseButton, PadButton, WheelDirection,
};
use crate::error::{KeymapWarning, Result};
use crate::keymap::{BindingSpec, Keymap, push_warning};

/// Analog value at which an absolute axis presses a button action.
pub const ANALOG_PRESS_THRESHOLD: f32 = 0.5;
/// An analog-pressed button releases below `threshold - hysteresis`.
pub const ANALOG_RELEASE_HYSTERESIS: f32 = 0.1;
/// Most buttons tracked as held at once; further presses are ignored.
pub const MAX_HELD_BUTTONS: usize = 64;
/// Most active holds (binding activations) at once.
pub const MAX_HOLDS: usize = 256;
/// Most text bytes collected per frame.
pub const MAX_TEXT_PER_FRAME: usize = 4096;
/// Most wheel clicks generated by one wheel event.
pub const MAX_WHEEL_CLICKS_PER_EVENT: u32 = 16;
/// Largest magnitude accepted for one relative motion event (device units).
pub const MAX_MOTION_PER_EVENT: f64 = 100_000.0;

/// A window-system-independent input event.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum RawEvent {
    /// A keyboard key changed state. `repeat` marks OS auto-repeat presses,
    /// which never trigger actions.
    Key {
        /// The physical key.
        key: KeyCode,
        /// New state.
        pressed: bool,
        /// Auto-repeat.
        repeat: bool,
    },
    /// A mouse button changed state.
    MouseButton {
        /// Which button.
        button: MouseButton,
        /// New state.
        pressed: bool,
    },
    /// Raw relative mouse motion (device units, `+x` right, `+y` down);
    /// feeds [`AnalogAxis::MouseX`]/[`AnalogAxis::MouseY`].
    MouseMotion {
        /// Horizontal movement.
        dx: f64,
        /// Vertical movement.
        dy: f64,
    },
    /// Cursor position in window pixels (tracked, not an axis).
    CursorMoved {
        /// X from the left edge.
        x: f64,
        /// Y from the top edge.
        y: f64,
    },
    /// The cursor left the window.
    CursorLeft,
    /// Wheel movement in notches (`+y` away from the user, `+x` right).
    /// Feeds [`AnalogAxis::WheelX`]/[`AnalogAxis::WheelY`] and the
    /// `WheelUp`/`WheelDown`/`WheelLeft`/`WheelRight` buttons (one click per
    /// whole notch, fractions accumulate).
    Wheel {
        /// Horizontal notches.
        dx: f32,
        /// Vertical notches.
        dy: f32,
    },
    /// A gamepad button changed state.
    PadButton {
        /// Which button.
        button: PadButton,
        /// New state.
        pressed: bool,
    },
    /// A gamepad axis moved to an absolute position (`-1..=1`, triggers
    /// `0..=1`). Relative axes are ignored here.
    PadAxis {
        /// Which axis.
        axis: AnalogAxis,
        /// New position.
        value: f32,
    },
    /// The window system's view of the held modifiers.
    Modifiers(Modifiers),
    /// A typed character (delivered to the topmost context if it takes
    /// text; control characters are dropped).
    Text(char),
    /// The window lost focus: everything is released.
    FocusLost,
}

/// Snapshot of one action for the current frame.
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct ActionState {
    /// Held at the end of the frame.
    pub pressed: bool,
    /// Press edges during the frame.
    pub presses: u16,
    /// Release edges during the frame.
    pub releases: u16,
    /// Axis actions: held digital values plus absolute axes, clamped to
    /// `-1..=1`. Button actions: `1.0` while pressed, else `0.0`.
    pub value: f32,
    /// Axis actions: sum of relative-axis movement during the frame,
    /// scaled. Button actions: `0.0`.
    pub delta: f32,
}

impl ActionState {
    /// Whether the action was pressed at least once this frame.
    #[must_use]
    pub fn just_pressed(&self) -> bool {
        self.presses > 0
    }

    /// Whether the action was released at least once this frame.
    #[must_use]
    pub fn just_released(&self) -> bool {
        self.releases > 0
    }
}

#[derive(Debug, Clone)]
struct DigitalBinding {
    action: ActionId,
    chord: Chord,
    value: f32,
    policy: ModifierPolicy,
}

#[derive(Debug, Clone)]
struct AnalogBinding {
    action: ActionId,
    axis: AnalogAxis,
    scale: f32,
    deadzone: f32,
}

#[derive(Debug, Clone, Default)]
struct CompiledContext {
    digital: Vec<DigitalBinding>,
    analog: Vec<AnalogBinding>,
}

#[derive(Debug, Clone)]
struct Hold {
    action: ActionId,
    context: ContextId,
    binding: usize,
    buttons: Vec<Button>,
}

#[derive(Debug, Clone)]
struct Pending {
    context: ContextId,
    candidates: Vec<usize>,
    depth: usize,
    deadline: Duration,
}

#[derive(Debug, Clone, Copy, Default)]
struct Accum {
    presses: u16,
    releases: u16,
    delta: f32,
}

/// Turns raw events into action states according to a registry, a keymap
/// and the stack of active contexts.
#[derive(Debug, Clone)]
pub struct InputMapper {
    registry: Registry,
    /// The keymap last compiled (kept to recompile when actions or
    /// contexts are registered later).
    keymap: Keymap,
    compiled: Vec<CompiledContext>,
    timeout: Duration,
    /// Active contexts with their activation serial.
    active: Vec<(ContextId, u64)>,
    serial: u64,
    down: Vec<Button>,
    key_mods: Modifiers,
    reported_mods: Modifiers,
    holds: Vec<Hold>,
    pending: Option<Pending>,
    live: Vec<bool>,
    analog_pressed: Vec<bool>,
    modifier_held: Vec<bool>,
    accum: Vec<Accum>,
    absolute: [f32; AnalogAxis::ALL.len()],
    relative: [f64; AnalogAxis::ALL.len()],
    wheel_frac: [f32; 2],
    cursor: Option<(f64, f64)>,
    text_pending: String,
    text: String,
    states: Vec<ActionState>,
}

impl InputMapper {
    /// A mapper for `registry` with `keymap` compiled against it; no context
    /// is active yet. Returns the compile warnings too.
    #[must_use]
    pub fn new(registry: Registry, keymap: &Keymap) -> (Self, Vec<KeymapWarning>) {
        let n = registry.action_count();
        let mut m = Self {
            keymap: Keymap::new(),
            compiled: Vec::new(),
            timeout: Duration::ZERO,
            active: Vec::new(),
            serial: 0,
            down: Vec::new(),
            key_mods: Modifiers::empty(),
            reported_mods: Modifiers::empty(),
            holds: Vec::new(),
            pending: None,
            live: vec![false; n],
            analog_pressed: vec![false; n],
            modifier_held: vec![false; n],
            accum: vec![Accum::default(); n],
            absolute: [0.0; AnalogAxis::ALL.len()],
            relative: [0.0; AnalogAxis::ALL.len()],
            wheel_frac: [0.0; 2],
            cursor: None,
            text_pending: String::new(),
            text: String::new(),
            states: vec![ActionState::default(); n],
            registry,
        };
        let warnings = m.set_keymap(keymap);
        (m, warnings)
    }

    /// The registry.
    #[must_use]
    pub fn registry(&self) -> &Registry {
        &self.registry
    }

    /// The keymap in use.
    #[must_use]
    pub fn keymap(&self) -> &Keymap {
        &self.keymap
    }

    /// Replace the keymap. Every held binding is released (edges appear in
    /// the next snapshot) and a pending sequence is dropped.
    pub fn set_keymap(&mut self, keymap: &Keymap) -> Vec<KeymapWarning> {
        self.release_holds(|_| true);
        self.pending = None;
        self.keymap = keymap.clone();
        let (compiled, warnings) = compile(&self.registry, keymap);
        for w in &warnings {
            tracing::debug!(warning = %w, "keymap compile");
        }
        self.compiled = compiled;
        self.timeout = Duration::from_millis(u64::from(keymap.sequence_timeout_ms()));
        warnings
    }

    /// Register another action on the running mapper (plugins, §2) and
    /// recompile the keymap so bindings that name it take effect. Active
    /// contexts, held buttons and holds of unchanged bindings are kept; a
    /// pending sequence is dropped. Compile warnings are logged.
    ///
    /// # Errors
    ///
    /// Those of [`Registry::add_action`]; nothing changes on error.
    pub fn register_action(&mut self, def: ActionDef) -> Result<ActionId> {
        let id = self.registry.add_action(def)?;
        let n = self.registry.action_count();
        self.live.resize(n, false);
        self.analog_pressed.resize(n, false);
        self.modifier_held.resize(n, false);
        self.accum.resize(n, Accum::default());
        self.states.resize(n, ActionState::default());
        self.recompile();
        Ok(id)
    }

    /// Register another context on the running mapper (inactive until
    /// [`activate`](Self::activate)d); see [`register_action`](Self::register_action).
    ///
    /// # Errors
    ///
    /// Those of [`Registry::add_context`]; nothing changes on error.
    pub fn register_context(&mut self, def: ContextDef) -> Result<ContextId> {
        let id = self.registry.add_context(def)?;
        self.recompile();
        Ok(id)
    }

    /// Recompile the stored keymap against the grown registry, moving each
    /// hold to its binding's new index (holds whose binding vanished are
    /// released).
    fn recompile(&mut self) {
        self.pending = None;
        let (compiled, warnings) = compile(&self.registry, &self.keymap);
        for w in &warnings {
            tracing::debug!(warning = %w, "keymap compile");
        }
        let old = std::mem::replace(&mut self.compiled, compiled);
        let mut lost = Vec::new();
        for (k, h) in self.holds.iter_mut().enumerate() {
            let chord = old
                .get(h.context.index())
                .and_then(|c| c.digital.get(h.binding))
                .map(|d| &d.chord);
            let new_index = chord.and_then(|chord| {
                self.compiled.get(h.context.index()).and_then(|c| {
                    c.digital
                        .iter()
                        .position(|d| d.action == h.action && d.chord == *chord)
                })
            });
            match new_index {
                Some(j) => h.binding = j,
                None => lost.push(k),
            }
        }
        let mut k = 0;
        self.release_holds(|_| {
            let gone = lost.contains(&k);
            k += 1;
            gone
        });
    }

    // ----- contexts -------------------------------------------------------

    /// Activate `ctx` (or bring it to the top among equal priorities if it is
    /// already active). Activating an opaque context releases holds owned by
    /// contexts below it.
    pub fn activate(&mut self, ctx: ContextId) {
        let Some(def) = self.registry.context_def(ctx) else {
            return;
        };
        let opaque = def.opaque;
        self.serial += 1;
        let serial = self.serial;
        match self.active.iter_mut().find(|(c, _)| *c == ctx) {
            Some(entry) => entry.1 = serial,
            None => self.active.push((ctx, serial)),
        }
        self.pending = None;
        if opaque {
            let order = self.ordered();
            let pos = order.iter().position(|c| *c == ctx).unwrap_or(0);
            let below: Vec<ContextId> = order[pos + 1..].to_vec();
            self.release_holds(|h| below.contains(&h.context));
        }
    }

    /// Deactivate `ctx`, releasing every hold it owns.
    pub fn deactivate(&mut self, ctx: ContextId) {
        self.active.retain(|(c, _)| *c != ctx);
        if self.pending.as_ref().is_some_and(|p| p.context == ctx) {
            self.pending = None;
        }
        self.release_holds(|h| h.context == ctx);
    }

    /// Activate or deactivate.
    pub fn set_active(&mut self, ctx: ContextId, active: bool) {
        if active != self.is_active(ctx) {
            if active {
                self.activate(ctx);
            } else {
                self.deactivate(ctx);
            }
        }
    }

    /// Whether `ctx` is active.
    #[must_use]
    pub fn is_active(&self, ctx: ContextId) -> bool {
        self.active.iter().any(|(c, _)| *c == ctx)
    }

    /// Active contexts in resolution order: priority descending, then most
    /// recently activated first.
    #[must_use]
    pub fn ordered(&self) -> Vec<ContextId> {
        let mut v = self.active.clone();
        v.sort_by(|a, b| {
            let pa = self.priority(a.0);
            let pb = self.priority(b.0);
            pb.cmp(&pa).then(b.1.cmp(&a.1))
        });
        v.into_iter().map(|(c, _)| c).collect()
    }

    fn priority(&self, c: ContextId) -> i32 {
        self.registry
            .context_def(c)
            .map_or(i32::MIN, |d| d.priority)
    }

    fn is_opaque(&self, c: ContextId) -> bool {
        self.registry.context_def(c).is_some_and(|d| d.opaque)
    }

    // ----- events ---------------------------------------------------------

    /// Feed one event. `now` is a monotonic timestamp from any fixed epoch
    /// (used only for sequence timeouts).
    pub fn handle(&mut self, event: &RawEvent, now: Duration) {
        match *event {
            RawEvent::Key {
                key,
                pressed,
                repeat,
            } => {
                self.button(Button::Key(key), pressed, repeat, now);
                if key.modifier() != Modifiers::empty() {
                    self.key_mods = self.mods_from_keys();
                }
            }
            RawEvent::MouseButton { button, pressed } => {
                self.button(Button::Mouse(button), pressed, false, now);
            }
            RawEvent::PadButton { button, pressed } => {
                self.button(Button::Pad(button), pressed, false, now);
            }
            RawEvent::MouseMotion { dx, dy } => {
                self.add_relative(AnalogAxis::MouseX, dx);
                self.add_relative(AnalogAxis::MouseY, dy);
            }
            RawEvent::CursorMoved { x, y } => {
                if x.is_finite() && y.is_finite() {
                    self.cursor = Some((x, y));
                }
            }
            RawEvent::CursorLeft => self.cursor = None,
            RawEvent::Wheel { dx, dy } => {
                self.add_relative(AnalogAxis::WheelX, f64::from(dx));
                self.add_relative(AnalogAxis::WheelY, f64::from(dy));
                self.wheel_clicks(0, dx, WheelDirection::Right, WheelDirection::Left, now);
                self.wheel_clicks(1, dy, WheelDirection::Up, WheelDirection::Down, now);
            }
            RawEvent::PadAxis { axis, value } => {
                if !axis.is_relative() {
                    self.absolute[axis.index()] = if value.is_finite() {
                        value.clamp(-1.0, 1.0)
                    } else {
                        0.0
                    };
                }
            }
            RawEvent::Modifiers(m) => self.reported_mods = m,
            RawEvent::Text(c) => self.push_text(c),
            RawEvent::FocusLost => self.release_all(),
        }
    }

    /// Release every button, modifier, hold and pending sequence, and zero
    /// the gamepad axes (focus loss, keymap reload).
    pub fn release_all(&mut self) {
        self.down.clear();
        self.key_mods = Modifiers::empty();
        self.reported_mods = Modifiers::empty();
        self.pending = None;
        self.absolute = [0.0; AnalogAxis::ALL.len()];
        self.wheel_frac = [0.0; 2];
        self.release_holds(|_| true);
    }

    /// Finish the frame: expire a timed-out sequence, evaluate modifier holds
    /// and analog sources, and publish the snapshot read by
    /// [`state`](Self::state).
    pub fn update(&mut self, now: Duration) {
        self.expire_pending(now);
        let order = self.ordered();
        let mods = self.mods();

        // Modifier holds (§7.4). A matching modifier-only binding is a held
        // digital binding, so its `value` also counts towards an axis
        // action's value (§2, §5.1).
        let mut held = vec![false; self.live.len()];
        let mut modifier_value = vec![0.0f32; self.live.len()];
        for &c in &order {
            if let Some(cc) = self.compiled.get(c.index()) {
                for b in &cc.digital {
                    let s = b.chord.first();
                    let i = b.action.index();
                    if s.is_modifier_hold()
                        && mods_match(mods, s.mods(), b.policy).is_some()
                        && let Some(h) = held.get_mut(i)
                    {
                        *h = true;
                        if let Some(v) = modifier_value.get_mut(i) {
                            *v += b.value;
                        }
                    }
                }
            }
            if self.is_opaque(c) {
                break;
            }
        }
        self.modifier_held = held;

        // Analog sources: each goes to the first context (in order) that
        // binds it; an opaque context stops the search.
        let n = self.live.len();
        let mut abs_sum = vec![0.0f32; n];
        let mut delta = vec![0.0f32; n];
        let mut analog_max = vec![f32::NEG_INFINITY; n];
        for &axis in AnalogAxis::ALL {
            for &c in &order {
                let Some(cc) = self.compiled.get(c.index()) else {
                    continue;
                };
                let mut bound = false;
                for b in cc.analog.iter().filter(|b| b.axis == axis) {
                    bound = true;
                    let i = b.action.index();
                    if i >= n {
                        continue;
                    }
                    let kind = self.kind(b.action);
                    if axis.is_relative() {
                        if kind == ActionKind::Axis {
                            let v = (self.relative[axis.index()] * f64::from(b.scale)) as f32;
                            if v.is_finite() {
                                delta[i] += v;
                            }
                        }
                    } else {
                        let v = apply_deadzone(self.absolute[axis.index()], b.deadzone) * b.scale;
                        if v.is_finite() {
                            abs_sum[i] += v;
                            analog_max[i] = analog_max[i].max(v);
                        }
                    }
                }
                if bound || self.is_opaque(c) {
                    break;
                }
            }
        }
        for i in 0..n {
            // §7.5: the 0.5 press / 0.4 release hysteresis applies to button
            // actions only; an axis is pressed while |value| >= 0.5 (§2).
            let pressed = match self.kind(ActionId(i as u16)) {
                ActionKind::Button => {
                    let threshold = if self.analog_pressed[i] {
                        ANALOG_PRESS_THRESHOLD - ANALOG_RELEASE_HYSTERESIS
                    } else {
                        ANALOG_PRESS_THRESHOLD
                    };
                    analog_max[i] >= threshold
                }
                ActionKind::Axis => abs_sum[i].abs() >= ANALOG_PRESS_THRESHOLD,
            };
            self.analog_pressed[i] = pressed;
            self.refresh(ActionId(i as u16));
        }

        // Publish.
        for i in 0..n {
            let id = ActionId(i as u16);
            let acc = std::mem::take(&mut self.accum[i]);
            let digital: f32 = self
                .holds
                .iter()
                .filter(|h| h.action == id)
                .map(|h| self.hold_value(h))
                .sum::<f32>()
                + modifier_value.get(i).copied().unwrap_or(0.0);
            let pressed = self.live[i];
            let (value, d) = match self.kind(id) {
                ActionKind::Axis => (
                    sanitize((digital + abs_sum[i]).clamp(-1.0, 1.0)),
                    sanitize(acc.delta + delta[i]),
                ),
                ActionKind::Button => (if pressed { 1.0 } else { 0.0 }, 0.0),
            };
            self.states[i] = ActionState {
                pressed,
                presses: acc.presses,
                releases: acc.releases,
                value,
                delta: d,
            };
        }
        self.relative = [0.0; AnalogAxis::ALL.len()];
        self.text = std::mem::take(&mut self.text_pending);
    }

    // ----- snapshot -------------------------------------------------------

    /// The action's state in the current snapshot (default for a foreign id).
    #[must_use]
    pub fn state(&self, id: ActionId) -> ActionState {
        self.states.get(id.index()).copied().unwrap_or_default()
    }

    /// `state(id).pressed`.
    #[must_use]
    pub fn pressed(&self, id: ActionId) -> bool {
        self.state(id).pressed
    }

    /// `state(id).just_pressed()`.
    #[must_use]
    pub fn just_pressed(&self, id: ActionId) -> bool {
        self.state(id).just_pressed()
    }

    /// `state(id).value`.
    #[must_use]
    pub fn value(&self, id: ActionId) -> f32 {
        self.state(id).value
    }

    /// `state(id).delta`.
    #[must_use]
    pub fn delta(&self, id: ActionId) -> f32 {
        self.state(id).delta
    }

    /// Text typed during the frame (only while a text context is on top).
    #[must_use]
    pub fn text(&self) -> &str {
        &self.text
    }

    /// Last cursor position in window pixels, `None` outside the window.
    #[must_use]
    pub fn cursor(&self) -> Option<(f64, f64)> {
        self.cursor
    }

    /// Currently held modifiers.
    #[must_use]
    pub fn mods(&self) -> Modifiers {
        self.key_mods | self.reported_mods
    }

    /// Whether a sequence is waiting for its next stroke.
    #[must_use]
    pub fn sequence_pending(&self) -> bool {
        self.pending.is_some()
    }

    // ----- internals ------------------------------------------------------

    fn kind(&self, id: ActionId) -> ActionKind {
        self.registry
            .action_def(id)
            .map_or(ActionKind::Button, |d| d.kind)
    }

    fn hold_value(&self, h: &Hold) -> f32 {
        self.compiled
            .get(h.context.index())
            .and_then(|c| c.digital.get(h.binding))
            .map_or(0.0, |b| b.value)
    }

    fn mods_from_keys(&self) -> Modifiers {
        self.down
            .iter()
            .fold(Modifiers::empty(), |m, b| m | b.modifier())
    }

    fn is_down(&self, b: Button) -> bool {
        self.down.contains(&b)
    }

    fn add_relative(&mut self, axis: AnalogAxis, v: f64) {
        if v.is_finite() {
            let slot = &mut self.relative[axis.index()];
            *slot = (*slot + v.clamp(-MAX_MOTION_PER_EVENT, MAX_MOTION_PER_EVENT)).clamp(-1e9, 1e9);
        }
    }

    fn wheel_clicks(
        &mut self,
        slot: usize,
        v: f32,
        pos: WheelDirection,
        neg: WheelDirection,
        now: Duration,
    ) {
        if !v.is_finite() {
            return;
        }
        let acc = &mut self.wheel_frac[slot];
        *acc = (*acc + v).clamp(-1e6, 1e6);
        let mut clicks = 0;
        while clicks < MAX_WHEEL_CLICKS_PER_EVENT && self.wheel_frac[slot].abs() >= 1.0 {
            let dir = if self.wheel_frac[slot] > 0.0 {
                pos
            } else {
                neg
            };
            self.wheel_frac[slot] -= self.wheel_frac[slot].signum();
            self.press(Button::Wheel(dir), now);
            clicks += 1;
        }
        // Whatever could not be delivered is dropped, keeping the fraction.
        self.wheel_frac[slot] = self.wheel_frac[slot].fract();
    }

    fn push_text(&mut self, c: char) {
        if c.is_control() || self.text_pending.len() + c.len_utf8() > MAX_TEXT_PER_FRAME {
            return;
        }
        let top_takes_text = self
            .ordered()
            .first()
            .and_then(|c| self.registry.context_def(*c))
            .is_some_and(|d| d.text);
        if top_takes_text {
            self.text_pending.push(c);
        }
    }

    fn button(&mut self, b: Button, pressed: bool, repeat: bool, now: Duration) {
        if pressed {
            if repeat || self.is_down(b) || self.down.len() >= MAX_HELD_BUTTONS {
                return;
            }
            self.down.push(b);
            self.press(b, now);
        } else {
            let before = self.down.len();
            self.down.retain(|d| *d != b);
            if self.down.len() != before {
                self.release_holds(|h| h.buttons.contains(&b));
            }
        }
    }

    fn expire_pending(&mut self, now: Duration) {
        if self.pending.as_ref().is_some_and(|p| now >= p.deadline) {
            self.pending = None;
        }
    }

    /// Does pressing `b` complete `stroke`? `Some(true)` exact modifiers,
    /// `Some(false)` subset match.
    fn completes(&self, stroke: &Stroke, b: Button, policy: ModifierPolicy) -> Option<bool> {
        if !stroke.buttons().contains(&b) {
            return None;
        }
        if !stroke.buttons().iter().all(|x| *x == b || self.is_down(*x)) {
            return None;
        }
        let effective = self.mods() - stroke.own_modifiers();
        mods_match(effective, stroke.mods(), policy)
    }

    /// Bindings among `candidates` of `ctx` whose stroke `depth` is completed
    /// by `b`: `(exact-modifier matches, subset matches)`.
    fn matching(
        &self,
        ctx: ContextId,
        candidates: &[usize],
        depth: usize,
        b: Button,
    ) -> (Vec<usize>, Vec<usize>) {
        let Some(cc) = self.compiled.get(ctx.index()) else {
            return (Vec::new(), Vec::new());
        };
        let mut exact = Vec::new();
        let mut subset = Vec::new();
        for &i in candidates {
            let Some(binding) = cc.digital.get(i) else {
                continue;
            };
            let Some(stroke) = binding.chord.strokes().get(depth) else {
                continue;
            };
            match self.completes(stroke, b, binding.policy) {
                Some(true) => exact.push(i),
                Some(false) => subset.push(i),
                None => {}
            }
        }
        (exact, subset)
    }

    fn press(&mut self, b: Button, now: Duration) {
        self.expire_pending(now);
        if let Some(p) = self.pending.take() {
            let next = p.depth;
            let (exact, subset) = self.matching(p.context, &p.candidates, next, b);
            let found = if exact.is_empty() { subset } else { exact };
            if !found.is_empty() {
                self.resolve(p.context, found, next + 1, now);
                return;
            }
            // A modifier key (re-pressed between strokes, or needed by the
            // next stroke) or one button of a simultaneous chord the next
            // stroke still waits for leaves the sequence waiting; the press
            // is not resolved further.
            if !b.modifier().is_empty() || self.in_next_stroke(&p, b) {
                self.pending = Some(p);
                return;
            }
            // The sequence is broken; the press is handled normally.
        }
        // Two passes over the contexts: exact-modifier matches anywhere win
        // over subset matches, then context order decides.
        let order = self.ordered();
        for exact_pass in [true, false] {
            for &ctx in &order {
                let all: Vec<usize> = self
                    .compiled
                    .get(ctx.index())
                    .map(|cc| (0..cc.digital.len()).collect())
                    .unwrap_or_default();
                let (exact, subset) = self.matching(ctx, &all, 0, b);
                let found = if exact_pass { exact } else { subset };
                if !found.is_empty() {
                    self.resolve(ctx, found, 1, now);
                    return;
                }
                if self.is_opaque(ctx) {
                    break;
                }
            }
        }
    }

    /// Whether `b` is one button of some candidate's next stroke whose other
    /// buttons are not all held yet (a simultaneous chord in progress).
    fn in_next_stroke(&self, p: &Pending, b: Button) -> bool {
        let Some(cc) = self.compiled.get(p.context.index()) else {
            return false;
        };
        p.candidates.iter().any(|&i| {
            cc.digital
                .get(i)
                .and_then(|d| d.chord.strokes().get(p.depth))
                .is_some_and(|s| {
                    s.buttons().contains(&b)
                        && s.buttons().iter().any(|x| *x != b && !self.is_down(*x))
                })
        })
    }

    /// `found` bindings of `ctx` have matched `depth` strokes: fire the
    /// complete ones, or wait for the next stroke.
    fn resolve(&mut self, ctx: ContextId, found: Vec<usize>, depth: usize, now: Duration) {
        let Some(cc) = self.compiled.get(ctx.index()) else {
            return;
        };
        let complete: Vec<usize> = found
            .iter()
            .copied()
            .filter(|&i| {
                cc.digital
                    .get(i)
                    .is_some_and(|d| d.chord.strokes().len() == depth)
            })
            .collect();
        if complete.is_empty() {
            self.pending = Some(Pending {
                context: ctx,
                candidates: found,
                depth,
                deadline: now.saturating_add(self.timeout),
            });
            return;
        }
        for i in complete {
            self.activate_binding(ctx, i);
        }
    }

    fn activate_binding(&mut self, ctx: ContextId, i: usize) {
        let Some(binding) = self
            .compiled
            .get(ctx.index())
            .and_then(|c| c.digital.get(i))
        else {
            return;
        };
        let action = binding.action;
        let buttons = binding.chord.last().buttons().to_vec();
        let momentary = buttons.iter().any(|b| matches!(b, Button::Wheel(_)));
        if self
            .holds
            .iter()
            .any(|h| h.context == ctx && h.binding == i)
        {
            return;
        }
        if self.holds.len() >= MAX_HOLDS {
            return;
        }
        self.holds.push(Hold {
            action,
            context: ctx,
            binding: i,
            buttons,
        });
        self.refresh(action);
        if momentary {
            self.release_holds(|h| h.context == ctx && h.binding == i);
        }
    }

    fn release_holds(&mut self, mut pred: impl FnMut(&Hold) -> bool) {
        let mut affected = Vec::new();
        self.holds.retain(|h| {
            if pred(h) {
                affected.push(h.action);
                false
            } else {
                true
            }
        });
        for a in affected {
            self.refresh(a);
        }
    }

    /// Recompute whether `a` is held and record an edge if it changed.
    fn refresh(&mut self, a: ActionId) {
        let i = a.index();
        if i >= self.live.len() {
            return;
        }
        let now = self.holds.iter().any(|h| h.action == a)
            || self.analog_pressed[i]
            || self.modifier_held[i];
        if now != self.live[i] {
            self.live[i] = now;
            let acc = &mut self.accum[i];
            if now {
                acc.presses = acc.presses.saturating_add(1);
            } else {
                acc.releases = acc.releases.saturating_add(1);
            }
        }
    }
}

fn mods_match(held: Modifiers, required: Modifiers, policy: ModifierPolicy) -> Option<bool> {
    if held == required {
        Some(true)
    } else if policy == ModifierPolicy::Subset && held.contains(required) {
        Some(false)
    } else {
        None
    }
}

fn apply_deadzone(v: f32, dz: f32) -> f32 {
    if !v.is_finite() {
        return 0.0;
    }
    let a = v.abs();
    if a <= dz || dz >= 1.0 {
        0.0
    } else {
        v.signum() * ((a - dz) / (1.0 - dz)).min(1.0)
    }
}

fn sanitize(v: f32) -> f32 {
    if v.is_finite() { v } else { 0.0 }
}

/// Resolve a keymap's names against a registry.
fn compile(registry: &Registry, keymap: &Keymap) -> (Vec<CompiledContext>, Vec<KeymapWarning>) {
    let mut out = vec![CompiledContext::default(); registry.context_count()];
    let mut warnings = Vec::new();
    let mut unknown_ctx: Vec<String> = Vec::new();
    for (c, a, list) in keymap.iter() {
        let Some(ctx) = registry.context(c) else {
            if !unknown_ctx.iter().any(|u| u == c) {
                unknown_ctx.push(c.into());
                push_warning(&mut warnings, || KeymapWarning::UnknownContext(c.into()));
            }
            continue;
        };
        let Some(action) = registry.action(a) else {
            push_warning(&mut warnings, || KeymapWarning::UnknownAction {
                context: c.into(),
                action: a.into(),
            });
            continue;
        };
        let Some(def) = registry.action_def(action) else {
            continue;
        };
        let Some(cc) = out.get_mut(ctx.index()) else {
            continue;
        };
        for spec in list {
            match spec {
                BindingSpec::Digital { chord, value } => cc.digital.push(DigitalBinding {
                    action,
                    chord: chord.clone(),
                    value: if value.is_finite() {
                        value.clamp(-1.0, 1.0)
                    } else {
                        0.0
                    },
                    policy: def.modifiers,
                }),
                BindingSpec::Analog {
                    axis,
                    scale,
                    deadzone,
                } => cc.analog.push(AnalogBinding {
                    action,
                    axis: *axis,
                    scale: if scale.is_finite() { *scale } else { 0.0 },
                    deadzone: if deadzone.is_finite() {
                        deadzone.clamp(0.0, 0.99)
                    } else {
                        0.0
                    },
                }),
            }
        }
    }
    // A chord that is a proper prefix of a longer one in the same context
    // would make the longer one unreachable: disable the longer one.
    for (ci, cc) in out.iter_mut().enumerate() {
        let chords: Vec<Chord> = cc.digital.iter().map(|d| d.chord.clone()).collect();
        let ctx_name = registry
            .context_def(ContextId(ci as u16))
            .map(|d| d.name.clone())
            .unwrap_or_default();
        cc.digital.retain(|d| {
            let s = d.chord.strokes();
            let shadow = chords.iter().find(|other| {
                let o = other.strokes();
                o.len() < s.len() && s[..o.len()] == *o
            });
            if let Some(shadow) = shadow {
                push_warning(&mut warnings, || KeymapWarning::PrefixConflict {
                    context: ctx_name.clone(),
                    sequence: d.chord.to_string(),
                    stroke: shadow.to_string(),
                });
                false
            } else {
                true
            }
        });
    }
    (out, warnings)
}

