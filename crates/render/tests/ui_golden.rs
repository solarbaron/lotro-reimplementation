#[test]
fn ui_filters_golden() -> Result<(), RenderError> {
    golden_scene("ui_filters", |r| {
        // A framed badge with a transparent border and a soft alpha ramp.
        let badge = ui_texture(r, 16, 16, |x, y| {
            if x == 0 || y == 0 || x == 15 || y == 15 {
                [0; 4]
            } else {
                [(x * 16) as u8, 200, (y * 16) as u8, (x * 17).min(255) as u8]
            }
        })?;
        let (img, _) = render_ui(r, SIZE, UNORM, |p| {
            let at = |x, y, w, h| UiEntry::new(badge, [16, 16], UiRect::new(x, y, w, h));
            p.entry(&at(8, 8, 16, 16))
                .entry(&at(32, 8, 48, 48))
                .entry(&at(88, 8, 48, 48).with_filter(UiFilter::Nearest))
                .entry(&at(144, 8, 8, 8))
                .entry(&at(160, 8, 40, 40).with_alpha_threshold(0.5))
                .entry(
                    &at(208, 8, 40, 40)
                        .with_alpha_threshold(0.5)
                        .with_opacity(0.5),
                )
                .entry(&at(8, 72, 64, 64).with_rotations(&[UiRotation {
                    centre: [40.0, 104.0],
                    angles: [0.0, 0.0, 33.0],
                }]))
                .entry(&at(88, 72, 64, 64).with_rotations(&[UiRotation {
                    centre: [120.0, 104.0],
                    angles: [50.0, 0.0, 0.0],
                }]))
                .entry(&at(168, 72, 64, 64).with_rotations(&[UiRotation {
                    centre: [200.0, 104.0],
                    angles: [0.0, 60.0, 20.0],
                }]))
                .entry(&at(8, 160, 240, 80).with_opacity(0.6));
        })?;
        r.destroy_texture(badge);
        Ok(img)
    })
}
