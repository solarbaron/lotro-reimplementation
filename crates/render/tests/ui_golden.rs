//! Golden images of the UI pass (`docs/specs/render.md` §6.13): Tile addressing, the clip at
//! the root (unrotated and turned), the clip chain with a mode-0 child window, external
//! content, the round minimap, a P1-shaped radar, and the filters, threshold, opacity and
//! rotations together.
//!
//! The scenes render into `Rgba8Unorm` targets: there the UI pass always blends stored
//! values, so the images are the same on backends with and without non-sRGB views (GL uses
//! the linear fallback on sRGB targets, render.md §6.4; `ui_pass.rs` covers that path).
//! Every canvas is generated by `ui_common`. Regenerate with
//! `TESSERA_BLESS=1 cargo test -p tessera-render --test ui_golden`.

#[path = "support/golden.rs"]
mod golden;
#[path = "support/gpu.rs"]
mod gpu;
#[path = "ui_common/mod.rs"]
mod ui_common;

use std::path::Path;

use tessera_render::{
    Filter, OffscreenFormat, PassSpace, Quad, RenderError, Renderer, RgbaImage, UiAddressing,
    UiClip, UiEntry, UiFilter, UiRect, UiRotation, UiSource, Wrap,
};
use ui_common::{P1, SIZE_P1, disc_alpha, render_ui, solid, ui_texture};

const SIZE: (u32, u32) = (256, 256);
const UNORM: OffscreenFormat = OffscreenFormat::Rgba8Unorm;

fn check(name: &str, img: &RgbaImage) {
    golden::check(
        &Path::new(env!("CARGO_MANIFEST_DIR")).join(format!("tests/golden/{name}.png")),
        img,
        golden::Tolerance::default(),
    );
}

/// Render twice (determinism) and compare with the golden image.
fn golden_scene(
    name: &str,
    scene: impl Fn(&mut Renderer<'static>) -> Result<RgbaImage, RenderError>,
) -> Result<(), RenderError> {
    let Some(mut r) = gpu::headless_renderer([0.0; 4]) else {
        return Ok(());
    };
    let img = scene(&mut r)?;
    let again = scene(&mut r)?;
    assert!(img == again, "{name}: render is not deterministic");
    check(name, &img);
    Ok(())
}

/// Vertical and horizontal stripes with a diagonal, opaque.
fn stripes(x: u32, y: u32) -> [u8; 4] {
    let v = if x == y { 250 } else { 0 };
    [
        (x * 8) as u8,
        if (y / 4).is_multiple_of(2) { 200 } else { 60 },
        v,
        255,
    ]
}

#[test]
fn ui_tile_golden() -> Result<(), RenderError> {
    golden_scene("ui_tile", |r| {
        let tile = ui_texture(r, 32, 32, stripes)?;
        let tile_at = |s: f32| UiAddressing::Tile { node_scale: [s, s] };
        let (img, _) = render_ui(r, SIZE, UNORM, |p| {
            p.entry(
                &UiEntry::new(tile, [32, 32], UiRect::new(8, 8, 200, 100))
                    .with_addressing(tile_at(1.0)),
            )
            .entry(
                &UiEntry::new(tile, [32, 32], UiRect::new(8, 120, 240, 128))
                    .with_addressing(tile_at(1.5)),
            );
        })?;
        r.destroy_texture(tile);
        Ok(img)
    })
}

#[test]
fn ui_clip_golden() -> Result<(), RenderError> {
    golden_scene("ui_clip", |r| {
        let root_tex = ui_texture(r, 100, 100, |x, y| {
            [40, 120 + (x % 50) as u8, 60 + (y % 64) as u8, 255]
        })?;
        let nested_tex = ui_texture(r, 70, 30, |x, y| {
            [
                230,
                (x * 3) as u8,
                (y * 8) as u8,
                if x % 10 < 8 { 255 } else { 128 },
            ]
        })?;
        let (img, _) = render_ui(r, SIZE, UNORM, |p| {
            for (origin, z) in [((8, 8), 0.0f32), ((136, 136), 30.0)] {
                let root = UiRect::new(origin.0, origin.1, 100, 100);
                let nested = UiRect::new(origin.0 + 60, origin.1 + 20, 70, 30);
                let rot = [UiRotation::z(
                    [origin.0 as f32 + 50.0, origin.1 as f32 + 50.0],
                    z,
                )];
                let clip = [UiClip::new(root, 0)];
                p.entry(&UiEntry::new(root_tex, [100, 100], root).with_rotations(&rot))
                    .entry(
                        &UiEntry::new(nested_tex, [70, 30], nested)
                            .with_rotations(&rot)
                            .with_clips(&clip),
                    );
            }
        })?;
        r.destroy_texture(root_tex);
        r.destroy_texture(nested_tex);
        Ok(img)
    })
}

#[test]
fn ui_clip_chain_golden() -> Result<(), RenderError> {
    golden_scene("ui_clip_chain", |r| {
        let p_tex = solid(r, 96, 96, [60, 60, 160, 255])?;
        let c_tex = solid(r, 60, 60, [60, 160, 60, 255])?;
        let k_tex = ui_texture(r, 60, 20, |x, _| [220, 200, (x * 4) as u8, 255])?;
        let none = UiRotation::default();
        let (img, _) = render_ui(r, SIZE, UNORM, |pass| {
            // Cells: (c) own-surface child turned by 30; (d) mode-0 child, parent turned by 30;
            // (d) mode-0 child past its parent; (b) own-surface child past its parent.
            let cells = [
                ((0, 0), true, 30.0f32, 0.0f32, 12),
                ((128, 0), false, 0.0, 30.0, 12),
                ((0, 128), false, 0.0, 0.0, 50),
                ((128, 128), true, 0.0, 0.0, 50),
            ];
            for ((ox, oy), child_surface, child_z, parent_z, child_dx) in cells {
                let parent = UiRect::new(ox + 16, oy + 16, 96, 96);
                let child = UiRect::new(parent.x + child_dx, parent.y + 18, 60, 60);
                let control = UiRect::new(child.x + 25, child.y + 20, 60, 20);
                let pc = [parent.x as f32 + 48.0, parent.y as f32 + 48.0];
                let cc = [child.x as f32 + 30.0, child.y as f32 + 30.0];
                let p_rot = UiRotation::z(pc, parent_z);
                let c_rot = UiRotation::z(cc, child_z);
                pass.entry(&UiEntry::new(p_tex, [96, 96], parent).with_rotations(&[p_rot]));
                if child_surface {
                    pass.entry(
                        &UiEntry::new(c_tex, [60, 60], child)
                            .with_rotations(&[c_rot, p_rot])
                            .with_clips(&[UiClip::new(parent, 1)]),
                    )
                    .entry(
                        &UiEntry::new(k_tex, [60, 20], control)
                            .with_rotations(&[none, c_rot, p_rot])
                            .with_clips(&[UiClip::new(child, 1), UiClip::new(parent, 2)]),
                    );
                } else {
                    pass.entry(
                        &UiEntry::new(k_tex, [60, 20], control)
                            .with_rotations(&[none, p_rot])
                            .with_clips(&[UiClip::new(child, 1), UiClip::new(parent, 1)]),
                    );
                }
            }
        })?;
        for t in [p_tex, c_tex, k_tex] {
            r.destroy_texture(t);
        }
        Ok(img)
    })
}

#[test]
fn ui_external_golden() -> Result<(), RenderError> {
    golden_scene("ui_external", |r| {
        let portrait = r.create_offscreen_target(32, 32, UNORM)?;
        let mut frame = r.begin_offscreen_frame(&portrait)?;
        frame
            .pass("portrait", PassSpace::Screen)
            .premultiplied_alpha()
            .quad(Quad::screen_rect(4.0, 4.0, 20.0, 24.0).with_color([0.9, 0.6, 0.2, 1.0]))
            .quad(Quad::screen_rect(24.0, 4.0, 1.0, 24.0).with_color([0.9, 0.6, 0.2, 0.5]))
            .quad(Quad::screen_rect(10.0, 10.0, 16.0, 8.0).with_color([0.1, 0.3, 1.0, 0.4]));
        r.end_frame(frame)?;
        let tex = r.register_target_texture(&portrait, Filter::Nearest, Wrap::Clamp)?;
        let light = solid(r, 1, 1, [230, 230, 220, 255])?;
        let ext = |dest| UiEntry::new(tex, [32, 32], dest).with_source(UiSource::Premultiplied);
        let rot = [UiRotation::z([200.0, 200.0], 20.0)];
        let (img, _) = render_ui(r, SIZE, UNORM, |p| {
            p.entry(&UiEntry::new(light, [1, 1], UiRect::new(128, 0, 128, 256)))
                .entry(&ext(UiRect::new(8, 8, 32, 32)))
                .entry(&ext(UiRect::new(136, 8, 32, 32)))
                .entry(&ext(UiRect::new(8, 56, 96, 96)))
                .entry(&ext(UiRect::new(150, 56, 96, 96)))
                .entry(&ext(UiRect::new(168, 168, 64, 64)).with_rotations(&rot));
        })?;
        r.destroy_texture(tex);
        r.destroy_texture(light);
        Ok(img)
    })
}

#[test]
fn ui_round_minimap_golden() -> Result<(), RenderError> {
    golden_scene("ui_round_minimap", |r| {
        let radar = ui_texture(r, 170, 170, |x, y| {
            let grid = if x % 20 == 0 || y % 20 == 0 { 40 } else { 0 };
            [
                (x + 40) as u8 - grid,
                (y + 60) as u8 - grid,
                90,
                disc_alpha(x, y),
            ]
        })?;
        let (img, _) = render_ui(r, SIZE, UNORM, |p| {
            p.entry(&UiEntry::new(
                radar,
                [170, 170],
                UiRect::new(43, 43, 170, 170),
            ));
        })?;
        r.destroy_texture(radar);
        Ok(img)
    })
}

