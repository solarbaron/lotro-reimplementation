//! The runtime: raw events in, per-frame action states and UI offers out
//! (`docs/specs/keymap.md` §7, decision 0014).
//!
//! Frame protocol (§7.1):
//!
//! 1. feed every window/device event, in arrival order, with
//!    [`InputMapper::handle`] (no UI) or [`InputMapper::handle_with`] (a UI
//!    attached: events are offered to a [`UiSink`] in order);
//! 2. with a UI attached, call [`InputMapper::offer_pending`] once after the
//!    last raw event;
//! 3. call [`InputMapper::update`] once, which publishes a snapshot;
//! 4. read the snapshot ([`InputMapper::state`], [`InputMapper::text`])
//!    until the next `update`.
//!
//! Edges (`presses`, `releases`) and relative deltas that happen between two
//! `update` calls all land in the second snapshot, so nothing is lost when a
//! key is pressed and released inside one frame. The snapshot shows **game
//! holds** only: a hold whose Start the UI consumed never shows.
//!
//! The context stack has two bands (§3): the **UI band**, a list of owned,
//! prioritised entries pushed and popped by the UI, consulted first; and the
//! **game band**, contexts activated by code and ordered by priority.

